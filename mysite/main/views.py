def get_products():
    prods=pd.DataFrame(conn.execute(text("SELECT * FROM fixjob.produktai")).fetchall())

    return prods.to_dict(orient='records')


def products(request):
    items_per_page = 12
    page = request.GET.get('page', 1)

    # Assuming prods is your queryset
    prods = get_products()
    paginator = Paginator(prods, items_per_page)
    try:
        items = paginator.page(page)
    except PageNotAnInteger:
        # If the page is not an integer, deliver the first page.
        items = paginator.page(1)
    except EmptyPage:
        # If the page is out of range (e.g., 9999), deliver the last page.
        items = paginator.page(paginator.num_pages)

    context = {
        'items': items,
    }

    return render(request, 'prods.html', context)


