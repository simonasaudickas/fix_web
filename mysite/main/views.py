def payment(request):
    stripe.api_key = settings.STRIPE_SECRET_KEY
    publishable_key = settings.STRIPE_PUBLISHABLE_KEY
    token = None

    if request.method == 'POST':
        token = request.POST.get('stripeToken')  # Get the token generated by Stripe.js
    amount = 100  # Get the amount from the form or model
    button_amount = amount*100
    currency = 'eur'  # Get the currency from the form or model

    description = "USB raktas"
    item_desc = 'Mikroschema, kuria galima panaudoti perkelti duomenis is vienos saugojamos vietos i kita.'
    if token:
        try:
                # Create a charge using the token
            charge = stripe.Charge.create(
                amount= amount*100,  # Amount in cents
                currency=currency,
                description=description,
                source=token,
            )
            return render(request, 'success.html')
        except stripe.error.CardError as e:
            # Display an error message to the user
            return render(request, 'error.html', {'error': e.error.message})

    return render(request, 'payment.html', {'pub_key':publishable_key, 'amount':amount, 'desc':description,'cur':currency, 'item_desc':item_desc, 'but':button_amount})


